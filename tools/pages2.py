def where(t):
    return ['Бургас'] * bool(t['burgas']) + ['Варна'] * bool(t['varna'])


def price_from(t):
    return min(int(x[1].split()[0]) for x in (t['burgas'], t['varna']) if x)


def build_therapy(t):
    path = f'terapii/{t["slug"]}/'
    crumbs = [('', 'Начало'), ('terapii/', 'СПА терапии'), (path, t['short'])]
    meta = []
    if t['burgas']:
        meta.append(('Бургас', e(f'{t["burgas"][0]} – {t["burgas"][1]}')))
    if t['varna']:
        meta.append(('Варна', e(f'{t["varna"][0]} – {t["varna"][1]}')))
    acts = ([('btn-dark', BOOK_BURGAS, 'Резервирай в Бургас')] if t['burgas'] else []) + \
           ([varna_call() if t['burgas'] else ('btn-dark', f'tel:{TEL_VARNA}', 'Обадете се за час')] if t['varna'] else [])

    def body(p):
        s = page_hero(p, crumbs, 'СПА терапии · ' + ' и '.join(where(t)), e(t['name']), e(t['intro'][0]), image=t['img'], meta=meta, actions=acts)
        inner = (head_block('За терапията', 'Как протича') + prose(t['intro'][1:]) if len(t['intro']) > 1 else '')
        s += section(inner + ben_cols(t['benefits']))
        others = [x for x in THERAPIES if x['slug'] != t['slug'] and set(where(x)) & set(where(t))][:3]
        s += related(p, 'Други терапии', [(f'terapii/{x["slug"]}/', f'от {price_from(x)} €', x['short']) for x in others])
        s += cta_band(p)
        return s
    return page(path, t['title'], t['desc'], body, crumbs, [service_ld(t['name'], str(price_from(t)), where(t))], current='terapii/')


