def legal_html(lines):
    out, lst = [], []
    for ln in lines:
        ln = ln.strip()
        if not ln or ln == '***':
            continue
        if ln.endswith(';') or (ln[0].islower() and len(ln) < 120):
            lst.append(ln)
            continue
        if lst:
            out.append('<ul class="checklist">' + ''.join(f'<li>{e(x)}</li>' for x in lst) + '</ul>')
            lst = []
        if len(ln) < 80 and not ln.endswith(('.', ':', '!', '?')):
            out.append(f'<h2 class="h3">{e(ln)}</h2>')
        else:
            out.append(f'<p>{e(ln)}</p>')
    if lst:
        out.append('<ul class="checklist">' + ''.join(f'<li>{e(x)}</li>' for x in lst) + '</ul>')
    return '<div class="prose legal">' + ''.join(out) + '</div>'


